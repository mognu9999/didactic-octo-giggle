// Латиница, похожая на кириллицу, и ноль-вместо-"о" — частые способы обхода.
const FOLD = {
  a: 'а', c: 'с', e: 'е', o: 'о', p: 'р', x: 'х', y: 'у', k: 'к', m: 'м', t: 'т', h: 'н', b: 'в', 0: 'о',
};
function fold(text) {
  return text.replace(/[a-z0]/g, (ch) => FOLD[ch] || ch);
}

function variants(text) {
  const v1 = lightNormalize(text).slice(0, 4000);
  const v2 = fold(v1);
  const v3 = collapseSpacedLetters(v2);
  return [...new Set([v1, v2, v3])];
}

// ---------------------------------------------------------------------------
// Свой список запрещённых слов и фраз (blocklist.txt)
// ---------------------------------------------------------------------------

let customRegexes = [];

function parseBlocklist(content) {
  const out = [];
  for (const rawLine of String(content).split(/\r?\n/)) {
    let line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const exactEnd = line.endsWith('$');
    if (exactEnd) line = line.slice(0, -1).trim();
    if (!line) continue;
    const body = lightNormalize(line)
      .split(/\s+/)
      .map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
      .join('\\s+');
    out.push(new RegExp(`${B}${body}${exactEnd ? E : ''}`, 'i'));
  }
  return out;
}

function loadBlocklist(filePath) {
  try {
    customRegexes = parseBlocklist(fs.readFileSync(filePath, 'utf8'));
    return customRegexes.length;
  } catch (e) {
    customRegexes = [];
    if (e.code !== 'ENOENT') console.error('Не удалось прочитать blocklist:', e.message);
    return 0;
  }
}

// Возвращает название категории или null.
function checkForbidden(text) {
  if (!text) return null;
  const vs = variants(text);
  for (const cat of CATEGORIES) {
    for (const re of cat.regexes) {
      for (const v of vs) if (re.test(v)) return cat.title;
    }
  }
  for (const re of customRegexes) {
    for (const v of vs) if (re.test(v)) return 'свой список (blocklist.txt)';
  }
  return null;
}

