// Местоимения и обращения, наличие которых рядом со "смягчённым" словом
// говорит о том, что оно адресовано конкретному человеку.
const PRONOUNS = [
  'ты', 'тебя', 'тебе', 'тобой', 'тобою',
  'вы', 'вас', 'вам', 'вами',
  'он', 'она', 'они', 'его', 'ее', 'её', 'их', 'ему', 'ей', 'им', 'ими',
  'я', 'меня', 'мне', 'мной', 'мною',
];

const CONTEXT_WINDOW = 3; // слов до и после

// Таблица замен "маскировочных" символов на похожие русские буквы
const LEET_MAP = {
  '0': 'о', '3': 'з', '4': 'ч', '6': 'б', '1': 'i',
  a: 'а', e: 'е', o: 'о', p: 'р', c: 'с', y: 'у', x: 'х', k: 'к', h: 'н',
  b: 'в', m: 'м', t: 'т', n: 'п',
};

// Невидимые символы нулевой ширины, мягкий перенос, управляющие метки
// направления — часто вставляют между буквами, чтобы обойти фильтр ("х​у​й").
const INVISIBLE_RE = /[\u00AD\u034F\u061C\u115F\u1160\u17B4\u17B5\u180E\u200B-\u200F\u202A-\u202E\u2060-\u2064\u2066-\u2069\uFEFF]/g;

function lightNormalize(text) {
  // Лёгкая нормализация — только регистр, ё→е и удаление невидимых символов,
  // БЕЗ подмены цифр/латиницы. Используется для разбиения на слова и поиска
  // местоимений/упоминаний, чтобы не портить [id123|Имя].
  if (!text) return '';
  return text.replace(INVISIBLE_RE, '').toLowerCase().replace(/ё/g, 'е');
}

function normalize(text) {
  if (!text) return '';
  let t = lightNormalize(text);
  t = t.replace(/[0-9a-z]/gi, (ch) => LEET_MAP[ch] || ch);
  // убираем точки/тире/подчёркивания/звёздочки между буквами одного слова
  // (обход "х.у.й") — но НЕ пробелы, пробел всегда настоящая граница слова.
  t = t.replace(/([а-я])[.\-_*]+(?=[а-я])/g, '$1');
  return t;
}

function buildRootsRegex(roots) {
  const parts = roots.map((root) => {
    let r = root;

    const needStart = r.startsWith('^');
    if (needStart) r = r.slice(1);

    const needEnd = r.endsWith('!');
    if (needEnd) r = r.slice(0, -1);

    const inner = r
      .split('')
      .map((ch) => {
        const escaped = ch.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        // Между буквами корня допускаем до двух "склеивающих" символов
        // обфускации — но НЕ пробел и НЕ другие буквы/цифры, иначе слова
        // на стыке могут случайно образовать матный корень.
        return `${escaped}+[.\\-_*]{0,2}`;
      })
      .join('');

    const prefix = needStart ? '(?<![а-я])' : '';
    const suffix = needEnd ? '(?![а-я])' : '';
    return `${prefix}${inner}${suffix}`;
  });

  return new RegExp(`(?:${parts.join('|')})`, 'i');
}

const DIRECT_REGEX = buildRootsRegex(DIRECT_ROOTS);
const CONTEXTUAL_REGEX = buildRootsRegex(CONTEXTUAL_ROOTS);

// "х у й", "п и з д е ц": три и более одиночные буквы подряд через пробелы
// склеиваем в слово и проверяем отдельно. Настоящих одиночных-слов из трёх
// подряд почти не бывает, а у букв вроде "х", "й", "л" самостоятельных слов нет.
function collapseSpacedLetters(normalizedText) {
  return normalizedText.replace(
    /(?<![а-я])[а-я](?:[ \t.\-_*]+[а-я]){2,}(?![а-я])/g,
    (run) => run.replace(/[ \t.\-_*]+/g, '')
  );
}

function hasMentionMarker(word) {
  // Упоминание вида [id123|Имя] рядом со словом — тоже сигнал, что фраза
  // адресована конкретному человеку.
  return /\[id\d+\|/.test(word);
}

// options.strict — для пользователей, у которых включена защита (деф+):
// "мягкие" слова (хуйня, говно, тупой...) считаются нарушением всегда, без
// проверки на местоимение рядом — заменяем ЛЮБОЙ оскорбительный/матерный
// контекст.
function containsProfanity(text, options = {}) {
  if (!text) return false;

  const normalized = normalize(text);

  // 1) Прямые оскорбления/мат — всегда, без вопросов.
  if (DIRECT_REGEX.test(normalized)) return true;

  // 1.1) То же, но для слов, разбитых пробелами по буквам ("х у й").
  const collapsed = collapseSpacedLetters(normalized);
  if (collapsed !== normalized) {
    if (DIRECT_REGEX.test(collapsed)) return true;
    if (options.strict && CONTEXTUAL_REGEX.test(collapsed)) return true;
  }

  // 1.5) Строгий режим: мягкие слова тоже считаются, контекст не нужен.
  if (options.strict && CONTEXTUAL_REGEX.test(normalized)) return true;

  // 2) "Мягкие" слова — только если рядом есть местоимение/обращение.
  const words = lightNormalize(text).split(/\s+/).filter(Boolean);
  for (let i = 0; i < words.length; i++) {
    if (!CONTEXTUAL_REGEX.test(normalize(words[i]))) continue;

    const from = Math.max(0, i - CONTEXT_WINDOW);
    const to = Math.min(words.length - 1, i + CONTEXT_WINDOW);
    for (let j = from; j <= to; j++) {
      if (j === i) continue;
      const w = words[j].replace(/[^а-я]/gi, '');
      if (PRONOUNS.includes(w) || hasMentionMarker(words[j])) {
        return true;
      }
    }
  }

  return false;
}

module.exports = { containsProfanity, normalize, lightNormalize, collapseSpacedLetters };
