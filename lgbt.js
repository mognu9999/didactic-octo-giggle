// Детектор ЛГБТ-тематики. Самодостаточный модуль (ничего не импортирует).
//
// Ловит корни слов (лгбт, гей, лесби..., трансгендер, квир и т.д.), в том числе
// с обфускацией: "л.г.б.т", "л г б т", "г-е-й", невидимые символы, латиница
// вместо русских букв ("гeй").
//
// Чтобы добавить своё слово — допишите регулярку в LGBT_PATTERNS.

const INVISIBLE_RE = /[\u00AD\u034F\u061C\u115F\u1160\u17B4\u17B5\u180E\u200B-\u200F\u202A-\u202E\u2060-\u2064\u2066-\u2069\uFEFF]/g;

const LATIN_TO_CYR = {
  a: 'а', e: 'е', o: 'о', p: 'р', c: 'с', y: 'у', x: 'х', k: 'к', h: 'н', b: 'в', m: 'м', t: 'т',
  '0': 'о', '3': 'з', '6': 'б',
};

const LGBT_PATTERNS = [
  // аббревиатура
  'лгбт',
  'lgbt',
  // русские слова ("(?<![а-я])" — не искать в середине чужого слова)
  '(?<![а-я])ге(?:й|и|ев|ю|ям|ях|ями)(?![а-я])', // гей, геи, геев... (но не "геймер", "гейзер")
  '(?<![а-я])гейск',
  'гейпарад',
  '(?<![а-я])лесби',
  '(?<![а-я])лезб',
  '(?<![а-я])бисексуал',
  '(?<![а-я])пансексуал',
  '(?<![а-я])асексуал',
  '(?<![а-я])гомосексуал',
  '(?<![а-я])гомосек',
  '(?<![а-я])гомофоб',
  '(?<![а-я])транссексуал',
  '(?<![а-я])трансгендер',
  '(?<![а-я])трансвест',
  '(?<![а-я])трансфоб',
  '(?<![а-я])квир',
  '(?<![а-я])фембой',
  '(?<![а-я])небинарн',
  '(?<![а-я])камингаут',
  'однополы[а-я]*\\s+(?:любов|брак|отношен|пар|семь)',
  'смен[аыуе]\\s+пола',
  // английские слова
  '(?<![a-z])gays?(?![a-z])',
  '(?<![a-z])lesbian',
  '(?<![a-z])bisexual',
  '(?<![a-z])homosexual',
  '(?<![a-z])transgender',
  '(?<![a-z])queer',
];

const LGBT_REGEX = new RegExp(`(?:${LGBT_PATTERNS.join('|')})`, 'i');

function base(text) {
  return String(text || '').replace(INVISIBLE_RE, '').toLowerCase().replace(/ё/g, 'е');
}

function homoglyph(t) {
  return t.replace(/[a-z0-9]/g, (ch) => LATIN_TO_CYR[ch] || ch);
}

// Склеиваем "л.г.б.т", "г-е-й" и "л г б т" (3+ одиночные буквы подряд).
function glue(t) {
  return t
    .replace(/([a-zа-я])[.\-_*]+(?=[a-zа-я])/g, '$1')
    .replace(/(?<![a-zа-я])[a-zа-я](?:[ \t.\-_*]+[a-zа-я]){2,}(?![a-zа-я])/g, (run) =>
      run.replace(/[ \t.\-_*]+/g, '')
    );
}

function containsLgbt(text) {
  if (!text) return false;
  const b = base(text);
  const variants = [b, glue(b), glue(homoglyph(b))];
  return variants.some((v) => LGBT_REGEX.test(v));
}

module.exports = { containsLgbt };
